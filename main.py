import random
import matplotlib.pyplot as plt

user_wins = 0
comp_wins = 0
ties = 0

print('Winning rules of the game ROCK PAPER SCISSORS are:\n'
      + "Rock vs Paper -> Paper wins \n"
      + "Rock vs Scissors -> Rock wins \n"
      + "Paper vs Scissors -> Scissors wins \n")

while True:
    print("\nEnter your choice \n 1 - Rock \n 2 - Paper \n 3 - Scissors \n")

    try:
        choice = int(input("Enter your choice: "))
    except ValueError:
        print("Invalid input! Please enter a number (1, 2, or 3).")
        continue

    while choice > 3 or choice < 1:
        choice = int(input('Enter a valid choice please : '))

    if choice == 1:
        choice_name = 'Rock'
    elif choice == 2:
        choice_name = 'Paper'
    else:
        choice_name = 'Scissors'

    print('User choice is:', choice_name)
    print("Now it's Computer's Turn...")

    comp_choice = random.randint(1, 3)

    if comp_choice == 1:
        comp_choice_name = 'Rock'
    elif comp_choice == 2:
        comp_choice_name = 'Paper'
    else:
        comp_choice_name = 'Scissors'

    print("Computer choice is:", comp_choice_name)
    print(choice_name, 'vs', comp_choice_name)

    if choice == comp_choice:
        result = "DRAW"
    elif (choice == 1 and comp_choice == 2) or (comp_choice == 1 and choice == 2):
        result = 'Paper'
    elif (choice == 1 and comp_choice == 3) or (comp_choice == 1 and choice == 3):
        result = 'Rock'
    elif (choice == 2 and comp_choice == 3) or (comp_choice == 2 and choice == 3):
        result = 'Scissors'

    if result == "DRAW":
        print("😑😑😑It's a TIE!😑😑😑")
        ties += 1
    elif result == choice_name:
        print("🤩🤩🤩YOU win!🤩🤩🤩")
        user_wins += 1
    else:
        print("💀💀💀Computer wins!💀💀💀")
        comp_wins += 1
    print("Do you want to play this game again? (Y/N)")
    ans = input().lower()
    if ans == 'n':
        break

print("\n👍👍👍👍Thanks for playing!👍👍👍👍")
print()
print()
print(f"🎊✨🎉Final Score🎉✨🎊-> You: {user_wins} | Computer: {comp_wins} | Ties: {ties}")
print()
print()
categories = ['User Wins', 'Computer Wins', 'Ties']
counts = [user_wins, comp_wins, ties]
colors = ['cyan', 'orange', 'magenta']

explode=[0.2,0,0]
def make_autopct(values):
    def my_autopct(pct):
        total = sum(values)
        val = int(round(pct*total/100.0))
        return '{v:d}\n({p:.1f}%)'.format(p=pct, v=val) if val > 0 else ''
    return my_autopct
plt.figure(figsize=(5, 5))
if sum(counts) > 0:
  plt.pie(counts,
            labels=categories,
            colors=colors,
            explode=explode,
            startangle=90,
            autopct=make_autopct(counts))
  plt.title('Game Results: Rock Paper Scissors')
  plt.show()
else:
    print("😔😔No games were played, so no chart to show!😔😔")